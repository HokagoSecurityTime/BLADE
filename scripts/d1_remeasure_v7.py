"""D1: re-measure detection / false-positive rate and p95 latency after the LoRA v7 switch, with the EXISTING scripts/attack_sim.py CLI
(same arguments as verification/METRICS.md: -n 20 --prepare-demo) plus matched direct backend requests — a copy of verification/measure_presentation.py
that writes into its own directory instead of overwriting verification/METRICS.md (the 2026-10-31 record stays).

Preconditions: demo backend 9000, admin API 8100 and proxy 8080 running as local processes with BLADE_LORA_MODEL=blade-qwen-lora-v7
(training/lora/README_serve_v7.md), the 7 demo policies generated by the v7 model and approved (ACTIVE).
Usage: python -X utf8 scripts/d1_remeasure_v7.py [--out verification/remeasure_v7_<date>] [--backend http://127.0.0.1:9000] [-n 20]
"""
from __future__ import annotations
import argparse, hashlib, json, os, subprocess, sys, time
from datetime import datetime, timezone
from pathlib import Path

import httpx, jwt

ROOT = Path(__file__).resolve().parents[1]; sys.path.insert(0, str(ROOT))
from scripts.attack_sim import cases, metrics, percentile  # noqa: E402


def env_from_dotenv() -> dict:
    env = os.environ.copy()
    for line in (ROOT / '.env').read_text(encoding='utf-8-sig').splitlines():
        if line.startswith(('BLADE_JWT_SECRET=', 'BLADE_POLICY_POLL_SEC=')):
            k, v = line.split('=', 1); env[k] = v.strip().strip('"').strip("'")
    env['PYTHONPATH'] = str(ROOT); return env


def main() -> None:
    ap = argparse.ArgumentParser(); ap.add_argument('--out', type=Path, default=ROOT / f"verification/remeasure_v7_{datetime.now().strftime('%Y%m%d')}")
    ap.add_argument('--proxy', default='http://127.0.0.1:8080'); ap.add_argument('--admin', default='http://127.0.0.1:8100'); ap.add_argument('--backend', default='http://127.0.0.1:9000')
    ap.add_argument('-n', type=int, default=20); a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True); env = env_from_dotenv()
    sim = ROOT / 'scripts/attack_sim.py'; sim_hash = hashlib.sha256(sim.read_bytes()).hexdigest()
    with httpx.Client(timeout=15) as c:
        before = c.get(a.admin + '/policies').raise_for_status().json()
        try: ps = c.get(os.getenv('BLADE_OLLAMA_URL', 'http://127.0.0.1:11434') + '/api/tags').json().get('models', [])
        except Exception: ps = []
    (a.out / 'metrics-policies-before.json').write_text(json.dumps(before, indent=2, ensure_ascii=False), encoding='utf-8')
    started = datetime.now(timezone.utc).isoformat()
    cmd = [sys.executable, str(sim), '-n', str(a.n), '--prepare-demo', '--proxy', a.proxy, '--admin', a.admin, '--output', str(a.out / 'metrics-proxy.json')]
    with (a.out / 'metrics-attack-sim.log').open('wb') as log:
        rc = subprocess.run(cmd, cwd=ROOT, env=env, stdout=log, stderr=subprocess.STDOUT).returncode
    print('attack_sim exit:', rc, flush=True)
    if rc: raise SystemExit('attack_sim failed; see metrics-attack-sim.log')
    proxy = json.loads((a.out / 'metrics-proxy.json').read_text(encoding='utf-8'))
    direct = []
    with httpx.Client(timeout=15) as c:
        for case in cases():
            admin = case.user == 'admin_1'
            tok = jwt.encode(dict(sub=case.user, roles=['admin'] if admin else ['user'], tenant_id='org_2' if case.user == 'user_99' else 'org_1',
                                  membership='premium' if admin else 'basic', exp=int(time.time()) + 3600), env['BLADE_JWT_SECRET'], algorithm='HS256')
            for _ in range(a.n):
                t0 = time.perf_counter()
                try: code = c.get(a.backend + case.path, headers={'Authorization': 'Bearer ' + tok}).status_code
                except httpx.HTTPError: code = 0
                direct.append(dict(label=case.label, kind=case.kind, path=case.path, status=code, latency_ms=(time.perf_counter() - t0) * 1000))
        after = c.get(a.admin + '/policies').raise_for_status().json()
    restored = sorted(before, key=lambda p: p['id']) == sorted(after, key=lambda p: p['id'])
    (a.out / 'metrics-direct.json').write_text(json.dumps(direct, indent=1), encoding='utf-8')
    dl = [r['latency_ms'] for r in direct]; d50, d95 = percentile(dl, .5), percentile(dl, .95)
    s = proxy['summary']; groups = proxy.get('groups') or []   # attack_sim: groups = per (label, kind) metrics
    labels = {(p['endpoint']['method'], p['endpoint']['path']): p['label'] for p in before}
    details = dict(measured_at_utc=started, attack_sim_sha256=sim_hash, attack_sim_hash_unchanged=hashlib.sha256(sim.read_bytes()).hexdigest() == sim_hash, policies_restored=restored,
                   ollama_models=[m.get('name') for m in ps], lora_model=os.getenv('BLADE_LORA_MODEL'), min_confidence=os.getenv('BLADE_LORA_MIN_CONFIDENCE'),
                   proxy_summary=s, direct=dict(n=len(direct), errors=sum(r['status'] != 200 for r in direct), p50_ms=d50, p95_ms=d95), delta_p95_ms=s['p95_ms'] - d95,
                   policies_before={f'{k[0]} {k[1]}': v for k, v in labels.items()})
    (a.out / 'metrics-details.json').write_text(json.dumps(details, indent=2, ensure_ascii=False), encoding='utf-8')
    md = ['# LoRA v7 전환 후 재측정 (demo_backend, attack_sim 기존 CLI)', '', f"측정 시각(UTC) {started}; 모델 {details['lora_model']} (MIN_CONFIDENCE {details['min_confidence']}); attack_sim.py 해시 불변 {details['attack_sim_hash_unchanged']}; 정책 복원 {restored}.", '',
          '| 지표 | 측정값 |', '|---|---:|', f"| 전체 탐지율 TP/(TP+FN) | {s.get('detection_rate')} |", f"| 전체 오탐율 FP/(FP+TN) | {s.get('false_positive_rate')} |",
          f"| 프록시 요청 수 / 오류 | {len(proxy.get('requests', []))} / {s.get('errors')} |", f"| 프록시 p50 / p95 | {s['p50_ms']:.3f} / {s['p95_ms']:.3f} ms |",
          f"| 백엔드 직접 요청 수 / 비-200 | {len(direct)} / {details['direct']['errors']} |", f"| 백엔드 직접 p50 / p95 | {d50:.3f} / {d95:.3f} ms |", f"| **프록시 추가 지연 p95** | **{s['p95_ms'] - d95:+.3f} ms** |", '',
          '## 측정 전 정책(label)', '', '| endpoint | label |', '|---|---|'] + [f'| {k} | {v} |' for k, v in details['policies_before'].items()]
    if groups:
        cols = ['TP', 'FN', 'FP', 'TN', 'errors', 'detection_rate', 'false_positive_rate', 'p50_ms', 'p95_ms']
        md += ['', '## label·구분별 (attack_sim groups)', '', '| label | kind | ' + ' | '.join(cols) + ' |', '|---|---|' + '---:|' * len(cols)]
        md += [f"| {g.get('label')} | {g.get('kind')} | " + ' | '.join('' if g.get(k) is None else (f'{g[k]:.3f}' if isinstance(g[k], float) else str(g[k])) for k in cols) + ' |' for g in groups]
    (a.out / 'METRICS_v7.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    print(json.dumps({k: v for k, v in details.items() if k != 'policies_before'}, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
